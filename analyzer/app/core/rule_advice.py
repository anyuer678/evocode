# 通用兜底：未命中规则库时给出结构化建议（引用位置与规则消息）
_GENERIC_ADVICE = (
    "该规则命中的问题点需要结合上下文判断影响；修复前先确认触发场景。",
    "定位到具体文件与行后：先复现问题 → 确认修复方案 → 修改并补测试 → 回归验证。",
)


def advice_for(rule_key: str, file_path: str, message: str) -> tuple[str, str]:
    """返回 (影响, 可操作修复)。规则库命中则用规则建议，否则通用建议。"""
    impact, fix = _GENERIC_ADVICE
    # 最长前缀匹配：完整 key > 语言前缀（如 "java:S107" > "java:"）
    candidates = [k for k in _RULE_ADVICE if rule_key.startswith(k)]
    if candidates:
        best = max(candidates, key=len)
        impact, fix = _RULE_ADVICE[best]
    # 通用建议中带上具体位置与规则消息，避免空泛
    if impact == _GENERIC_ADVICE[0]:
        impact = f"{message}（{file_path} 位置，规则 {rule_key}）"
    return impact, fix
